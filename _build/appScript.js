/* 军标 */
function drawUnits(day){
  hit=[];
  const placed=[];
  const overlapScore=(x,y,w,h)=>{
    let s=0;
    for(let i=0;i<placed.length;i++){
      const p=placed[i];
      const ox=Math.min(x+w,p.x+p.w)-Math.max(x,p.x);
      const oy=Math.min(y+h,p.y+p.h)-Math.max(y,p.y);
      if(ox>0 && oy>0) s += ox*oy;
    }
    return s;
  };
  const list = UNITS.filter(u=> day>=u.life[0] && day<=u.life[1]+0.001);
  const soloDim = SOLO ? (u=> u.id===SOLO ? 1 : .2) : (u=>1);
  // 先画解放军再画国军，避免相互压盖
  list.sort((a,b)=> (a.s==="k"?0:1)-(b.s==="k"?0:1));
  list.forEach(u=>{
    const pos = pathPos(u,day);
    const [gx,gy]=px(pos[0],pos[1]);
    const main = u.s==="p" ? "#9c2f24" : "#2c4a63";
    const fade = (day>u.life[1]-0.6 ? Math.max(.35,(u.life[1]-day+0.6)) : 1) * soloDim(u);

    const sym = OPT.sym==="sym", tier = /兵团|绥靖区/.test(u.n), nar = W<560;
    let w,h;
    if(sym){
      w = tier?(nar?21:24):(nar?15:18);
      h = tier?(nar?13:14):(nar?9:11);
    }
    else{
      ctx.font="600 "+(W<560?8.8:9.5)+"px "+FONT_SANS;
      const tw=ctx.measureText(u.n).width;
      w=tw+(W<560?8:10); h=W<560?13:15;
    }

    // 在拥挤处做二维避让：在包围盒网格上找遮挡面积最小、离原点最近的位置
    const stepX=w+9, stepY=h+5;
    let bestOx=0, bestOy=0, bestS=Infinity;
    for(let ry=-4;ry<=4;ry++){
      for(let rx=-3;rx<=3;rx++){
        const ox=rx*stepX, oy=ry*stepY;
        const bx=gx-w/2+ox, by=gy-h/2+oy;
        if(bx<6||bx+w>W-6||by<6||by+h>H-6) continue;
        const s=overlapScore(bx,by,w,h)*4+(Math.abs(rx)*2+Math.abs(ry))*7;
        if(s<bestS){ bestS=s; bestOx=ox; bestOy=oy; }
      }
    }
    const bx=gx-w/2+bestOx, by=gy-h/2+bestOy;
    placed.push({x:bx,y:by,w:w,h:h});

    ctx.globalAlpha=fade;
    // 错位时用引线回到真实位置
    if(bestOx!==0 || bestOy!==0){
      ctx.strokeStyle=main; ctx.lineWidth=.9; ctx.globalAlpha=fade*0.4;
      ctx.beginPath(); ctx.moveTo(gx,gy);
      ctx.lineTo(bx+w/2, bestOy>0? by : by+h);
      ctx.stroke();
      ctx.globalAlpha=fade;
    }
    // 底板 / 军标
    if(!sym){
      ctx.fillStyle = u.s==="p" ? "rgba(156,47,36,.13)" : "rgba(44,74,99,.13)";
      ctx.fillRect(bx,by,w,h);
      ctx.strokeStyle=main; ctx.lineWidth=1.2;
      ctx.strokeRect(bx,by,w,h);
      // 顶部色带
      ctx.fillStyle=main;
      ctx.fillRect(bx,by,w,2.2);

      ctx.fillStyle=main;
      ctx.textAlign="center";
      ctx.fillText(u.n, bx+w/2, by+h/2+3.2);
    }else{
      // 1948 年参谋作业的符号：兵团级＝实顶杠＋团部方块，纵队级＝步兵交叉线
      ctx.fillStyle = u.s==="p" ? "rgba(156,47,36,.12)" : "rgba(44,74,99,.12)";
      ctx.fillRect(bx,by,w,h);
      ctx.strokeStyle=main; ctx.lineWidth=1.4;
      ctx.strokeRect(bx,by,w,h);
      if(tier){
        ctx.fillStyle=main; ctx.fillRect(bx,by,w,2.6);
        ctx.fillRect(bx+w/2-2.2,by+h/2-2.2,4.4,4.4);
      }else{
        ctx.lineWidth=1.1;
        ctx.beginPath();
        ctx.moveTo(bx+2.5,by+2.6); ctx.lineTo(bx+w-2.5,by+h-2.6);
        ctx.moveTo(bx+w-2.5,by+2.6); ctx.lineTo(bx+2.5,by+h-2.6);
        ctx.stroke();
      }
    }
    ctx.globalAlpha=1;

    hit.push({x:bx, y:by, w:w, h:h, id:u.id, cx:gx, cy:gy});
  });
}

