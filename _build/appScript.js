/* 折线→弯曲河形：Catmull-Rom 平滑 + 端点不动的横向摆动（自然河曲，不是直线） */
function catmullPath(pts, seg, amp, seed){
  const n=pts.length; if(n<2) return pts.slice();
  const out=[];
  for(let i=0;i<n-1;i++){
    const p0=pts[Math.max(0,i-1)], p1=pts[i], p2=pts[i+1], p3=pts[Math.min(n-1,i+2)];
    const dlon=p2[0]-p1[0], dlat=p2[1]-p1[1];
    const len=Math.hypot(dlon*COSL,dlat)||1;
    const nx=-dlat/len, ny=dlon/len;
    for(let j=0;j<seg;j++){
      if(i>0 && j===0) continue;
      const t=j/seg, t2=t*t, t3=t2*t;
      const lon=.5*(2*p1[0]+(-p0[0]+p2[0])*t+(2*p0[0]-5*p1[0]+4*p2[0]-p3[0])*t2+(-p0[0]+3*p1[0]-3*p2[0]+p3[0])*t3);
      const lat=.5*(2*p1[1]+(-p0[1]+p2[1])*t+(2*p0[1]-5*p1[1]+4*p2[1]-p3[1])*t2+(-p0[1]+3*p1[1]-3*p2[1]+p3[1])*t3);
      const w = amp ? Math.sin((i*seg+j)*0.86+seed)*amp*Math.sin(Math.PI*t) : 0;
      out.push([lon+nx*w, lat+ny*w]);
    }
  }
  out.push(pts[n-1].slice ? pts[n-1].slice() : pts[n-1]);
  return out;
}
