/* 当前时刻的插值工具 */
/* 计时：浏览器用 performance.now，无 performance 的环境退回 Date.now */
function nowMs(){ return (typeof performance!=="undefined" && performance.now) ? performance.now() : Date.now(); }
function pathPos(u, day){
  const p = u.path;
  if(day <= p[0][0]) return C(p[0][1]);
  if(day >= p[p.length-1][0]) return C(p[p.length-1][1]);
  for(let i=0;i<p.length-1;i++){
    const a=p[i], b=p[i+1];
    if(day>=a[0] && day<=b[0]){
      const t=(day-a[0])/((b[0]-a[0])||1);
      const e=t<.5 ? 2*t*t : 1-Math.pow(-2*t+2,2)/2;
      const A=C(a[1]), Bb=C(b[1]);
      return [A[0]+(Bb[0]-A[0])*e, A[1]+(Bb[1]-A[1])*e];
    }
  }
  return C(p[p.length-1][1]);
}

