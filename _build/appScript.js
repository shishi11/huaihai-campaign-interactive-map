/* 箭头 */
function drawArrows(day){
  ARROWS.forEach(ar=>{
    if(day<ar.d0 || day>ar.d1) return;
    const A=C(ar.a), Bb=C(ar.b);
    const [x1,y1]=px(A[0],A[1]), [x2,y2]=px(Bb[0],Bb[1]);
    const dx=x2-x1, dy=y2-y1, len=Math.hypot(dx,dy);
    if(len<2) return;
    const prog = Math.min(1, (day-ar.d0+1)/((ar.d1-ar.d0)+1));
    const ux=dx/len, uy=dy/len, nx=-uy, ny=ux;
    const bend = Math.min(46, len*0.28);
    const mx=(x1+x2)/2+nx*bend, my=(y1+y2)/2+ny*bend;
    const col = ar.s==="p" ? "rgba(156,47,36,.72)" : "rgba(44,74,99,.72)";

    // 曲线抽样
    const steps=26;
    const pts=[];
    for(let i=0;i<=steps;i++){
      const t=(i/steps)*prog;
      const q=(1-t)*(1-t), w=2*(1-t)*t, e=t*t;
      pts.push([q*x1+w*mx+e*x2, q*y1+w*my+e*y2]);
    }
    ctx.strokeStyle=col;
    ctx.lineWidth=(ar.t.length>4?2.6:2)*Math.min(1.35,view.z*0.9);
    ctx.beginPath();
    pts.forEach((p,i)=>{ i? ctx.lineTo(p[0],p[1]) : ctx.moveTo(p[0],p[1]); });
    ctx.stroke();

    // 箭头
    const tip=pts[pts.length-1], prev=pts[pts.length-2]||pts[0];
    const ang=Math.atan2(tip[1]-prev[1], tip[0]-prev[0]);
    const hl=8.5*Math.min(1.25,view.z*0.9);
    ctx.fillStyle=col;
    ctx.beginPath();
    ctx.moveTo(tip[0],tip[1]);
    ctx.lineTo(tip[0]-hl*Math.cos(ang-0.42), tip[1]-hl*Math.sin(ang-0.42));
    ctx.lineTo(tip[0]-hl*Math.cos(ang+0.42), tip[1]-hl*Math.sin(ang+0.42));
    ctx.closePath(); ctx.fill();

    // 标注
    if(prog>0.55){
      const mi=Math.floor(steps*0.5);
      const mp=pts[mi]||pts[0];
      ctx.font="10px "+FONT_SANS;
      ctx.textAlign="center";
      const tw=ctx.measureText(ar.t).width;
      ctx.fillStyle="rgba(242,236,221,.86)";
      ctx.fillRect(mp[0]-tw/2-3, mp[1]-6, tw+6, 13);
      ctx.fillStyle=ar.s==="p"?"#7c241c":"#22404f";
      ctx.fillText(ar.t, mp[0], mp[1]+4);
    }
  });
}

/* ---------- 细图附加图层 ---------- */
let HILLPTS=null;
function inPoly(poly,x,y){
  let c=false;
  for(let i=0,j=poly.length-1;i<poly.length;j=i++){
    const xi=poly[i][0], yi=poly[i][1], xj=poly[j][0], yj=poly[j][1];
    if(((yi>y)!==(yj>y)) && (x<(xj-xi)*(y-yi)/(yj-yi)+xi)) c=!c;
  }
  return c;
}
function buildHills(){
  HILLPTS=[];
  let sd=19481106;
  const rnd=()=>{ sd=(sd*1103515245+12345)&0x7fffffff; return sd/0x7fffffff; };
  HILLS.forEach(h=>{
    let w=Infinity,e=-Infinity,s=Infinity,n=-Infinity;
    h.pts.forEach(p=>{ w=Math.min(w,p[0]); e=Math.max(e,p[0]); s=Math.min(s,p[1]); n=Math.max(n,p[1]); });
    for(let lon=w; lon<=e; lon+=0.042){
      for(let lat=s; lat<=n; lat+=0.042){
        if(rnd()>h.d) continue;
        if(!inPoly(h.pts, lon, lat)) continue;
        HILLPTS.push([lon, lat, (rnd()-0.5)*2.4]);
      }
    }
  });
}
/* 山地晕纹：短促的三笔「山」形，密度低，只作地形暗示 */
